"""Neighbourhood and road clues: import, matching and scoring. No network, no database."""
from reliefnet import areas, geo
from reliefnet.areas import places
from reliefnet.parsing import location_clues, parse_message, road_forms

# Two wards side by side: ward 1 is west of 85.15, ward 2 is east of it.
WARDS = [
    {"num": 1, "name": "West Ward", "lat": 25.600, "lon": 85.140,
     "polygon": [[25.62, 85.13], [25.62, 85.15], [25.58, 85.15], [25.58, 85.13]]},
    {"num": 2, "name": "East Ward", "lat": 25.600, "lon": 85.160,
     "polygon": [[25.62, 85.15], [25.62, 85.17], [25.58, 85.17], [25.58, 85.15]]},
]
# About 1 km square, inside ward 2.
GREEN = [[25.610, 85.155], [25.610, 85.165], [25.600, 85.165], [25.600, 85.155]]
NBS = [
    {"id": "N1", "name": "Green Park Colony", "aliases": ["green park"], "ward": 2, "lat": 25.605, "lon": 85.160,
     "polygon": GREEN},
    {"id": "N2", "name": "Old Town", "aliases": [], "ward": 1, "lat": 25.590, "lon": 85.140, "polygon": None},
]
LMS = [
    {"id": "L1", "name": "Shiv Mandir", "aliases": ["mandir", "shiv temple"], "ward": 2, "kind": "temple",
     "lat": 25.6050, "lon": 85.1600},
    {"id": "L2", "name": "Shiv Mandir, West Ward", "aliases": ["shiv mandir"], "ward": 1, "kind": "temple",
     "lat": 25.5900, "lon": 85.1400},
]
LINES = {
    # The same name in two places; the importer adds the ward to each.
    "Road No.1, West Ward": [[[25.590, 85.135], [25.590, 85.145]]],
    "Road No.1, East Ward": [[[25.608, 85.156], [25.608, 85.164]]],
    "Station Road": [[[25.6052, 85.1500], [25.6052, 85.1690]]],
    "Main Road": [[[25.595, 85.131], [25.595, 85.169]]],
    "Lane near Shiv Mandir": [[[25.604, 85.159], [25.606, 85.161]]],
}
NB_NAMES = [(n["name"], n["aliases"]) for n in NBS]
LM_NAMES = [(l["name"], l["aliases"]) for l in LMS]
ROADS = [n for n in LINES if road_forms(n)]


def where(**kw) -> dict:
    args = {"landmark": "", "ward": 0, "location_text": "", "seed": "pytest", "neighbourhood": "", "road": ""}
    return geo.locate(LMS, WARDS, NBS, LINES, **{**args, **kw})


# ------------------------------------------------------------------ clues in a message
def test_road_names_that_people_type():
    assert "road 1" in road_forms("Road No.1, Lohanipur")
    assert road_forms("Lane near Shiv Mandir") == set()  # generated by the importer
    assert road_forms("Main Road") == set()  # only road words: fits every road
    assert ROADS == ["Road No.1, West Ward", "Road No.1, East Ward", "Station Road"]


def test_clues_match_neighbourhoods_and_roads():
    c = location_clues("5 log fanse hain green park mein, rd no. 1 ke paas", NB_NAMES, ROADS)
    assert c == {"neighbourhood": "Green Park Colony", "road": "Road No.1"}
    assert location_clues("Station road pe paani", NB_NAMES, ROADS)["road"] == "Station Road"
    assert location_clues("main road pe paani", NB_NAMES, ROADS) == {"neighbourhood": "", "road": ""}
    # A road whose words are only part of the matched landmark name is not a second clue.
    assert location_clues("kali mandir road ke paas", [], ["Kali Mandir Road"], taken=["kali mandir road"])["road"] == ""


def test_parse_message_returns_the_clues():
    d = parse_message("help 4 log Green Park road number 1, khana chahiye", LM_NAMES, NB_NAMES, ROADS)
    assert (d["neighbourhood"], d["road"]) == ("Green Park Colony", "Road No.1")
    # Without the lists the parser works as before.
    assert parse_message("help 4 log green park, khana chahiye")["neighbourhood"] == ""


def test_a_road_name_beats_a_generic_landmark_alias_inside_it():
    roads = ["Birla Mandir Road", "Malahi Pakdi Road"]
    d = parse_message("water entering house near Birla Mandir Road, 4 people", LM_NAMES, [], roads)
    assert (d["landmark"], d["road"]) == ("", "Birla Mandir Road")
    lm = [("Malahi Pakri", ["malahi pakdi"])]
    d = parse_message("4 log fanse hain Malahi Pakdi Road pe", lm, [], roads)
    assert (d["landmark"], d["road"]) == ("Malahi Pakri", "Malahi Pakdi Road")


# ------------------------------------------------------------------ scoring
def test_landmark_and_road_agree_and_the_point_moves_onto_the_road():
    loc = where(landmark="Shiv Mandir", ward=2, road="Station Road", neighbourhood="Green Park Colony")
    assert loc["geo_confidence"] == "high"
    assert (loc["landmark"], loc["road"], loc["neighbourhood"]) == ("Shiv Mandir", "Station Road", "Green Park Colony")
    assert abs(loc["lat"] - 25.6052) < 0.0005  # on the road, not 20 m beside the temple
    assert "road Station Road" in loc["why"]


def test_a_conflicting_clue_lowers_the_confidence():
    loc = where(landmark="Shiv Mandir", ward=2, neighbourhood="Old Town")
    assert loc["geo_confidence"] == "medium"
    assert "does not agree: neighbourhood Old Town" in loc["why"]


def test_the_neighbourhood_picks_between_two_landmarks_with_one_name():
    assert where(location_text="shiv mandir", neighbourhood="Old Town")["landmark"] == "Shiv Mandir, West Ward"
    assert where(location_text="shiv mandir", neighbourhood="green park")["landmark"] == "Shiv Mandir"


def test_road_and_neighbourhood_without_a_landmark():
    loc = where(road="Road No.1", neighbourhood="Green Park Colony")
    assert loc["road"] == "Road No.1, East Ward" and loc["ward"] == 2
    assert loc["geo_confidence"] == "medium"
    assert areas.point_in_polygon(loc["lat"], loc["lon"], GREEN)


def test_the_ward_picks_between_two_roads_with_one_name():
    loc = where(road="road no 1", ward=1)
    assert loc["road"] == "Road No.1, West Ward" and loc["geo_confidence"] == "medium"
    alone = where(road="Station Road")
    assert alone["road"] == "Station Road" and alone["geo_confidence"] == "low"


def test_neighbourhood_only_is_low_and_inside_it():
    loc = where(neighbourhood="green park")
    assert loc["geo_confidence"] == "low" and loc["ward"] == 2 and loc["landmark"] == ""
    assert areas.point_in_polygon(loc["lat"], loc["lon"], GREEN)
    clash = where(neighbourhood="green park", ward=1)
    assert clash["geo_confidence"] == "low" and clash["ward"] == 2
    assert "does not agree: ward 1" in clash["why"]


def test_old_callers_get_the_old_answers():
    assert where(ward=1)["geo_confidence"] == "low"
    none = where()
    assert none["geo_confidence"] == "none" and none["ward"] == 0
    assert where(landmark="Shiv Mandir", ward=2)["geo_confidence"] == "high"


# ------------------------------------------------------------------ OpenStreetMap import
def _square(lat, lon, d):
    return [{"lat": lat, "lon": lon}, {"lat": lat, "lon": lon + d}, {"lat": lat - d, "lon": lon + d},
            {"lat": lat - d, "lon": lon}, {"lat": lat, "lon": lon}]


def test_overpass_neighbourhoods_keep_their_outline():
    sq = _square(25.610, 85.155, 0.01)
    osm = {"elements": [
        {"type": "node", "id": 1, "lat": 25.605, "lon": 85.160,
         "tags": {"place": "suburb", "name": "Green Park Colony", "name:hi": "ग्रीन पार्क"}},
        {"type": "relation", "id": 2, "tags": {"place": "neighbourhood", "name": "Green Park Colony"},
         "members": [{"type": "way", "role": "outer", "geometry": sq[:3]},
                     {"type": "way", "role": "outer", "geometry": sq[2:]}]},
        {"type": "way", "id": 3, "geometry": _square(25.604, 85.143, 0.0003),  # a house, not a neighbourhood
         "tags": {"place": "neighbourhood", "name": "Friend's House"}},
        {"type": "node", "id": 4, "lat": 25.59, "lon": 85.14, "tags": {"place": "quarter", "name": "Colony"}},
        {"type": "node", "id": 5, "lat": 25.59, "lon": 85.14, "tags": {"place": "neighbourhood", "name": "Old Town"}},
        {"type": "node", "id": 6, "lat": 26.50, "lon": 85.14, "tags": {"place": "suburb", "name": "Far Town"}},
        {"type": "node", "id": 7, "lat": 25.59, "lon": 85.14, "tags": {"amenity": "school", "name": "A School"}},
    ]}
    rows = places.neighbourhoods_from_osm(osm, (25.58, 85.13, 25.62, 85.17))
    assert [(r["name"], r["osm"]) for r in rows] == [("Green Park Colony", "r2"), ("Old Town", "n5")]
    assert len(rows[0]["polygon"]) == 4 and rows[0]["alt"] == ["ग्रीन पार्क"]
    assert rows[1]["polygon"] is None


def test_neighbourhoods_get_a_ward_and_unique_names():
    osm = [{"osm": "n1", "name": "Old Town", "alt": [], "lat": 25.59, "lon": 85.14, "polygon": None},
           {"osm": "n2", "name": "Old Town", "alt": [], "lat": 25.59, "lon": 85.16, "polygon": None},
           {"osm": "n3", "name": "Outside", "alt": [], "lat": 25.70, "lon": 85.16, "polygon": None},
           {"osm": "w4", "name": "Green Park Colony", "alt": ["Green Park"], "lat": 25.605, "lon": 85.16,
            "polygon": GREEN}]
    out = places.neighbourhoods([("Hand Nagar", ["hand nagar", "nagar"], 25.61, 85.14)], osm, WARDS)
    assert [(n["name"], n["ward"], n["source"]) for n in out] == [
        ("Hand Nagar", 1, "hand"), ("Old Town, West Ward", 1, "osm"), ("Old Town, East Ward", 2, "osm"),
        ("Green Park Colony", 2, "osm")]
    assert out[0]["aliases"] == ["hand nagar"]  # "nagar" alone is generic
    assert "old town" in out[1]["aliases"] and "green park" in out[3]["aliases"]
    assert set(out[0]) == {"id", "name", "aliases", "ward", "lat", "lon", "polygon", "source"}


def test_a_neighbourhood_change_keeps_the_road_version(monkeypatch):
    name = "ganga_nagar"
    areas.region.cache_clear()
    roads, marks, junctions = areas.version(name), areas.landmark_version(name), areas.junction_version(name)
    w = areas.region(name).wards[0]
    extra = [{"osm": "n9", "name": "Pytest Nagar", "alt": [], "lat": w["lat"], "lon": w["lon"], "polygon": None}]
    monkeypatch.setattr(places, "load_neighbourhoods", lambda m: extra if m.NAME == name else [])
    areas.region.cache_clear()
    try:
        assert areas.version(name) == roads
        assert areas.junction_version(name) == junctions
        assert areas.landmark_version(name) != marks
        assert [n["name"] for n in areas.region(name).neighbourhoods] == ["Pytest Nagar"]
    finally:
        areas.region.cache_clear()


def test_patna_neighbourhoods_come_from_the_places_file():
    hoods = areas.region("patna").neighbourhoods
    assert len({n["id"] for n in hoods}) == len(hoods)
    assert all(n["ward"] and n["id"].startswith("N") for n in hoods)
    assert "Rajendra Nagar" in {n["name"] for n in hoods}
